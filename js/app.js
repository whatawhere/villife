function updateMediaPosition(force) {
  if (!mediaSession || typeof mediaSession.setPositionState !== "function") return;
  const now = Date.now();
  if (!force && now - lastPositionUpdate < 1000) return;
  const track = qIndex >= 0 ? queue[qIndex] : null;
  const duration = Number.isFinite(audio.duration) && audio.duration > 0
    ? audio.duration
    : track && Number.isFinite(Number(track.duration)) ? Number(track.duration) : 0;
  if (!Number.isFinite(duration) || duration <= 0) {
    mediaSession.setPositionState();
    return;
  }
  const currentTime = Number.isFinite(audio.currentTime) ? Math.max(audio.currentTime, 0) : 0;
  const playbackRate = Number.isFinite(audio.playbackRate) && audio.playbackRate > 0 ? audio.playbackRate : 1;
  try {
    mediaSession.setPositionState({
      duration: duration,
      playbackRate: playbackRate,
      position: Math.min(currentTime, duration)
    });
  } catch (error) {
    console.error("Could not update the system playback position.", error);
    return;
  }
  lastPositionUpdate = now;
}

function setupMediaSession() {
  if (!mediaSession) return;
  mediaSession.setActionHandler("play", () => {
    if (qIndex >= 0 && audio.paused) audio.play().catch(() => {});
  });
  mediaSession.setActionHandler("pause", pausePlayback);
  mediaSession.setActionHandler("previoustrack", previousTrack);
  mediaSession.setActionHandler("nexttrack", () => step(1));
  mediaSession.setActionHandler("seekto", event => {
    if (Number.isFinite(event.seekTime) && Number.isFinite(audio.duration))
      seekAudio(Math.min(Math.max(event.seekTime, 0), audio.duration));
  });
  mediaSession.setActionHandler("seekbackward", event => {
    const offset = Number.isFinite(event.seekOffset) ? event.seekOffset : 10;
    if (Number.isFinite(audio.duration))
      seekAudio(Math.max(audio.currentTime - offset, 0));
  });
  mediaSession.setActionHandler("seekforward", event => {
    const offset = Number.isFinite(event.seekOffset) ? event.seekOffset : 10;
    if (Number.isFinite(audio.duration))
      seekAudio(Math.min(audio.currentTime + offset, audio.duration));
  });
  mediaSession.setActionHandler("stop", () => {
    pausePlayback();
    seekAudio(0);
    updateMediaPosition(true);
  });
}

