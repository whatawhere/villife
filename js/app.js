async function doSearch(q) {
  lastQuery = q;
  searchError = false;
  results = [];
  playlists = [];
  renderForYouHome();
  setSearchArtwork(null);
  updateSection();
  if (!q.trim()) {
    renderResults();
    return;
  }
  if (!window.chrome || !window.chrome.webview) {
    if (SEARCH_WORKER) {
      const base = SEARCH_WORKER.replace(/\/+$/, "");
      for (let attempt = 0; attempt < 3; attempt++) {
        try {
          const [trackList, playlistList] = await Promise.all([
            fetch(base + "/search?q=" + encodeURIComponent(q)).then(response => response.ok ? response.json() : []),
            fetch(base + "/search/playlists?q=" + encodeURIComponent(q)).then(response => response.ok ? response.json() : [])
          ]);
          if (!Array.isArray(trackList) || trackList.length === 0) {
            await new Promise(resolve => setTimeout(resolve, 400));
            continue;
          }
          results = trackList.map(track => Object.assign({}, track, {
            stream: base + "/stream?id=" + encodeURIComponent(track.id || "")
          }));
          playlists = Array.isArray(playlistList) ? playlistList : [];
          searchError = false;
          renderResults();
          return;
        } catch (error) {}
      }
    }
    const needle = q.trim().toLocaleLowerCase();
    const playlistTracks = savedPlaylists.reduce((all, playlist) => all.concat(Array.isArray(playlist.tracks) ? playlist.tracks : []), []);
    const pool = uniqueSearchTracks(lib.concat(playlistTracks));
    results = pool.filter(track => {
      const title = String(track.title || "").toLocaleLowerCase();
      const artist = String(track.artist || "").toLocaleLowerCase();
      return title.includes(needle) || artist.includes(needle);
    });
    playlists = [];
    searchError = false;
    renderResults();
    return;
  }
  showSkeleton();
  const queries = await Promise.all([
    getJson("/api/search?q=" + encodeURIComponent(q)).then(data => ({ data: data })).catch(error => ({ error: error })),
    getJson("/api/search/playlists?q=" + encodeURIComponent(q)).then(data => ({ data: data })).catch(error => ({ error: error }))
  ]);
  if (lastQuery !== q) return;
  const trackQuery = queries[0];
  const playlistQuery = queries[1];
  if (trackQuery.error) console.error("Track search failed.", trackQuery.error);
  if (playlistQuery.error) console.error("Playlist search failed.", playlistQuery.error);
  searchError = !!trackQuery.error && !!playlistQuery.error;
  results = Array.isArray(trackQuery.data) ? uniqueSearchTracks(trackQuery.data) : [];
  playlists = Array.isArray(playlistQuery.data) ? playlistQuery.data : [];
  renderResults();
  warmTracks(results.slice(0, 3));
}

function trackSrc(tr) {
  if (tr.source === "spotify")
    return tr.spotifyMetadataVersion === 4 ? tr.stream || "" : "";
  return tr.stream || tr.preview || "";
}

function warmTracks(tracks) {
  tracks.forEach(track => {
    if (!track || !/^sc:/.test(track.id || "") || !track.stream) return;
    getJson("/api/warm?id=" + encodeURIComponent(track.id)).then(result => {
      if (!result.ready) console.error("Track preloading is unavailable.", track.id);
    }).catch(error => console.error("Track preloading failed.", track.id, error));
  });
}

function handlePlaybackError(error) {
  if (error && error.name === "AbortError") return;
  console.error("Playback could not start.", error);
  $("pl-play").classList.remove("loading");
  toast(t("playback_error"));
}

function loadTrack(tr) {
  const src = trackSrc(tr);
  if (audio.dataset.src === src) return;
  audio.dataset.src = src;
  if (!window.chrome || !window.chrome.webview) {
    if (window.__villifeHls) {
      window.__villifeHls.destroy();
      window.__villifeHls = null;
    }
    if (window.Hls && window.Hls.isSupported() && /\/stream\?id=/.test(src)) {
      const hls = new window.Hls({
        enableWorker: false,
        lowLatencyMode: false,
        manifestLoadingMaxRetry: 3,
        manifestLoadingRetryDelay: 1200,
        manifestLoadingMaxRetryTimeout: 45000,
        manifestLoadingTimeout: 45000
      });
      hls.loadSource(src);
      hls.attachMedia(audio);
      hls.on(window.Hls.Events.ERROR, (event, data) => {
        if (data && data.fatal) hls.destroy();
      });
      window.__villifeHls = hls;
      return;
    }
    if (audio.canPlayType("application/vnd.apple.mpegurl")) {
      audio.src = src;
      return;
    }
  }
  audio.src = src;
}

function playAt(list, index, source) {
  const track = list && list[index];
  const alreadyPlaying = !!(track && qIndex >= 0 && queue[qIndex] &&
    sameTrack(queue[qIndex], track) && !audio.ended);
  if (alreadyPlaying) {
    if (audio.paused) audio.play().catch(handlePlaybackError);
    return;
  }
  if (source) playbackSource = source;
  cancelCrossfade();
  const requestId = ++playbackRequestId;
  startTrack(list, index, requestId);
}

async function startTrack(list, index, requestId) {
  const tr = list[index];
  if (!tr) return;
  if (tr.source === "spotify" && tr.spotifyMetadataVersion !== 4) {
    try {
      await ensureSpotifyTrackResolved(tr);
    } catch (error) {
      console.error("Could not resolve Spotify track before playback.", tr.id, error);
    }
    if (requestId !== playbackRequestId) return;
    if (queue !== list || qIndex !== index) {
      queue = list;
      qIndex = index;
    }
    if (view === "library") saveLib();
    else if (activePlaylist && activePlaylist.tracks === list) savePlaylists();
    if (activePlaylistTracks === list) renderPlaylistDetail(activePlaylist, list);
    else if (view === "library") renderLibrary();
  }
  if (requestId !== playbackRequestId) return;
  if (!trackSrc(tr)) {
    if (tr.source === "spotify") toast(t("spotify_full_track_unavailable"));
    return;
  }
  if ($("settings-crossfade").checked) {
    try {
      await ensureAudioGraph();
    } catch (error) {
      console.error("Crossfade audio could not be initialized.", error);
      toast(t("playback_error"));
    }
    if (requestId !== playbackRequestId) return;
  }
  queue = list;
  qIndex = index;
  fillQueue(4);
  loadTrack(tr);
  audio.play().catch(handlePlaybackError);
  renderPlayer();
  refreshViews();
  preloadNextTrack();
}

function fillQueue(count) {
  if (view === "wave" && waveTracks.length) return 0;
  if (qIndex < 0 || !queue.length) return 0;
  if (queue === favorites || queue === lib || queue === results || queue === waveTracks ||
      queue === activePlaylistTracks || queue === activeArtistTracks) queue = queue.slice();
  const upcoming = queue.length - qIndex - 1;
  if (upcoming >= count) return 0;
  const seen = new Set();
  const collect = tracks => tracks.filter(track => {
    if (!track || !(trackSrc(track) || track.source === "spotify")) return false;
    if (queue.some(item => sameTrack(item, track)) || isNotInterested(track)) return false;
    const key = waveTrackKey(track);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  const playlistTracks = savedPlaylists.reduce((all, playlist) =>
    all.concat(Array.isArray(playlist.tracks) ? playlist.tracks : []), []);
  const others = collect(lib.concat(results, playlistTracks).filter(track => track && !isFavorite(track)));
  const liked = collect(favorites);
  const history = collect(historyTracks);
  const pool = others.length ? others.concat(liked)
    : liked.length ? liked.concat(history)
      : history;
  if (!pool.length) return 0;
  let anchor = queue[qIndex];
  let added = 0;
  const target = count - upcoming;
  while (added < target && pool.length) {
    const pick = wavePick(pool, anchor);
    if (!pick) break;
    queue.push(pick);
    anchor = pick;
    const at = pool.findIndex(track => sameTrack(track, pick));
    if (at >= 0) pool.splice(at, 1);
    added++;
  }
  if (added && view === "queue") renderQueue();
  return added;
}

function step(d, automatic) {
  const inWave = view === "wave" && waveTracks.length > 0;
  if (!inWave && d >= 0) fillQueue(4);
  const activeQueue = inWave ? waveTracks : queue;
  if (!activeQueue.length) return;
  if (inWave && activeQueue !== queue) queue = activeQueue;
  if (d > 0 && !automatic && qIndex >= 0 && activeQueue[qIndex] &&
      Number.isFinite(audio.currentTime) && audio.currentTime < 10) {
    recordWaveSkip(activeQueue[qIndex]);
  }
  if (d < 0) {
    let previousIndex = qIndex - 1;
    if (previousIndex < 0 && repeatMode === "all") previousIndex = activeQueue.length - 1;
    if (previousIndex < 0) return;
    playAt(activeQueue, previousIndex);
    return;
  }
  if (repeatMode === "one" && automatic && qIndex >= 0 && queue[qIndex]) {
    audio.currentTime = 0;
    audio.play().catch(handlePlaybackError);
    return;
  }
  let nextIndex = -1;
  if (inWave) {
    const current = activeQueue[qIndex];
    let picked = null;
    if (waveNextPick && activeQueue.some(track => sameTrack(track, waveNextPick)) &&
      !sameTrack(waveNextPick, current) && trackSrc(waveNextPick)) {
      picked = waveNextPick;
    } else {
      picked = wavePick(activeQueue, current);
    }
    waveNextPick = null;
    if (picked) nextIndex = activeQueue.findIndex(track => sameTrack(track, picked));
    if (nextIndex < 0) {
      const pool = (favorites.length ? favorites : lib).concat(results)
        .filter(track => !activeQueue.some(item => sameTrack(item, track)));
      const fresh = wavePick(pool, current);
      if (fresh) {
        waveTracks.push(fresh);
        queue = waveTracks;
        nextIndex = waveTracks.length - 1;
      }
    }
  } else if (shuffleEnabled && activeQueue.length > 1) {
    const candidates = activeQueue
      .map((track, index) => ({ track: track, index: index }))
      .filter(item => item.index !== qIndex && (trackSrc(item.track) || item.track.source === "spotify"));
    if (candidates.length) nextIndex = candidates[Math.floor(Math.random() * candidates.length)].index;
  } else if (qIndex + 1 < activeQueue.length) {
    for (let index = qIndex + 1; index < activeQueue.length; index++) {
      if (trackSrc(activeQueue[index]) || activeQueue[index].source === "spotify") {
        nextIndex = index;
        break;
      }
    }
  } else if (repeatMode === "all" && activeQueue.length) {
    nextIndex = activeQueue.findIndex(track => trackSrc(track) || track.source === "spotify");
  }
  if (nextIndex < 0 || (nextIndex === qIndex && !automatic)) {
    const playlistTracks = savedPlaylists.reduce((all, playlist) =>
      all.concat(Array.isArray(playlist.tracks) ? playlist.tracks : []), []);
    const pool = favorites.concat(lib, results, historyTracks, playlistTracks)
      .filter(track => track && (trackSrc(track) || track.source === "spotify") &&
        !sameTrack(track, activeQueue[qIndex]) && !isNotInterested(track));
    const fresh = wavePick(pool, activeQueue[qIndex]);
    if (fresh) {
      queue = activeQueue.concat(fresh);
      nextIndex = queue.length - 1;
    }
  }
  if (nextIndex < 0 || (nextIndex === qIndex && !automatic)) {
    const current = activeQueue[qIndex];
    const alternatives = activeQueue.map((track, index) => ({ track: track, index: index }))
      .filter(item => item.index !== qIndex && item.track &&
        (trackSrc(item.track) || item.track.source === "spotify"));
    if (alternatives.length) {
      const scored = alternatives.map(item =>
        ({ item: item, score: waveCompatibility(current, item.track) }));
      scored.sort((a, b) => b.score - a.score);
      nextIndex = scored[Math.floor(Math.random() * Math.min(3, scored.length))].item.index;
    }
  }
  if (nextIndex < 0 || (nextIndex === qIndex && !automatic)) {
    const current = activeQueue[qIndex];
    const anchorQueue = activeQueue;
    fetchSeedTracks(current).then(tracks => {
      const fresh = tracks.filter(track => !anchorQueue.some(item => sameTrack(item, track)));
      const pick = wavePick(fresh, current);
      if (!pick) return;
      queue = anchorQueue.concat(pick);
      playAt(queue, queue.length - 1);
    });
    return;
  }
  const track = (nextIndex < activeQueue.length ? activeQueue : queue)[nextIndex];
  if ($("settings-crossfade").checked && !audio.paused && !audio.ended && trackSrc(track) && nextIndex !== qIndex) {
    beginCrossfade(nextIndex < activeQueue.length ? activeQueue : queue, nextIndex, 0.35);
    return;
  }
  playAt(nextIndex < activeQueue.length ? activeQueue : queue, nextIndex);
}

function previousTrack() {
  if (qIndex < 0 || !queue[qIndex]) return;
  if (audio.currentTime > 3) {
    seekAudio(0);
    updateProgress();
    updateMediaPosition(true);
    return;
  }
  const currentTrack = queue[qIndex];
  const historyIndex = historyTracks.findIndex(track => sameTrack(track, currentTrack));
  const previous = historyTracks.slice(historyIndex >= 0 ? historyIndex + 1 : 0)
    .find(track => track && !sameTrack(track, currentTrack) && (trackSrc(track) || track.source === "spotify"));
  if (!previous) {
    step(-1);
    return;
  }
  const nextQueue = [previous, currentTrack].concat(
    queue.slice(qIndex + 1).filter(track => !sameTrack(track, previous) && !sameTrack(track, currentTrack))
  );
  playAt(nextQueue, 0, "history");
}

function playFromHistory(track) {
  if (!track) return;
  const currentTrack = qIndex >= 0 ? queue[qIndex] : null;
  const upcoming = qIndex >= 0 ? queue.slice(qIndex + 1) : queue.slice();
  const nextQueue = [track];
  if (currentTrack && !sameTrack(currentTrack, track)) nextQueue.push(currentTrack);
  upcoming.forEach(item => {
    if (!nextQueue.some(queued => sameTrack(queued, item))) nextQueue.push(item);
  });
  playAt(nextQueue, 0, "history");
}

