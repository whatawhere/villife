function renderLyrics(data, showLoadingDots) {
  const content = $("lyrics-content");
  clearTimeout(lyricsLoadingTimer);
  lyricsLoadingTimer = null;
  clearTimeout(lyricsSearchTimer);
  lyricsSearchTimer = null;
  if (lyricsScrollFrame) cancelAnimationFrame(lyricsScrollFrame);
  lyricsScrollFrame = 0;
  content.classList.remove("waiting-for-lyrics");
  content.innerHTML = "";
  parsedLyrics = [];
  activeLyricIndex = -1;
  finalLyricEndTime = Infinity;
  const synced = String(data.syncedLyrics || "");
  const timestampPattern = /\[(\d+):(\d{2})(?:\.(\d{1,3}))?\]([^\r\n]*)/g;
  let match;
  while ((match = timestampPattern.exec(synced)) !== null) {
    const fraction = match[3] || "";
    const milliseconds = fraction ? Number(("0." + fraction)) : 0;
    const time = Number(match[1]) * 60 + Number(match[2]) + milliseconds;
    const text = match[4].trim();
    if (text) parsedLyrics.push({ time: time, text: text });
  }
  const plain = String(data.plainLyrics || "").split(/\r?\n/).map(line => line.trim()).filter(Boolean);
  if (!parsedLyrics.length) parsedLyrics = plain.map(text => ({ time: null, text: text }));
  if (!parsedLyrics.length) {
    setNoLyricsState(true);
    return;
  }
  if (showLoadingDots) {
    const trackId = activeLyricsTrackId;
    content.appendChild(createLyricsLoading(lang === "en" ? "Lyrics found. Loading…" : "Текст найден. Загружаем…"));
    lyricsSearchTimer = setTimeout(() => {
      lyricsSearchTimer = null;
      if (trackId === activeLyricsTrackId) renderLyrics(data, false);
    }, 360);
    return;
  }
  if (parsedLyrics[0].time !== null) {
    const intervals = [];
    for (let i = 1; i < parsedLyrics.length; i++) {
      const interval = parsedLyrics[i].time - parsedLyrics[i - 1].time;
      if (interval > 0) intervals.push(interval);
    }
    intervals.sort((a, b) => a - b);
    const typicalInterval = intervals.length
      ? intervals[Math.floor((intervals.length - 1) / 2)]
      : 3;
    const pauseThreshold = Math.max(4.5, typicalInterval * 2.25);
    const linesWithPauses = [];
    parsedLyrics.forEach((line, index) => {
      linesWithPauses.push(line);
      const next = parsedLyrics[index + 1];
      const gap = next ? next.time - line.time : 0;
      if (next && gap > pauseThreshold) {
        const words = line.text.trim().split(/\s+/).length;
        const spokenDuration = Math.min(gap - 0.4, Math.max(1.2, words * 0.48));
        if (gap - spokenDuration >= 1.5)
          linesWithPauses.push({ time: line.time + spokenDuration, text: "", pause: true });
      }
    });
    parsedLyrics = linesWithPauses;
    const lastLine = parsedLyrics.filter(line => !line.pause).slice(-1)[0];
    if (lastLine) {
      const currentTrack = qIndex >= 0 ? queue[qIndex] : null;
      const duration = Number.isFinite(audio.duration) && audio.duration > 0
        ? audio.duration
        : currentTrack ? Number(currentTrack.duration) || 0 : 0;
      const wordCount = lastLine.text.trim().split(/\s+/).length;
      const spokenDuration = Math.max(3.5, wordCount * 0.7);
      finalLyricEndTime = duration > lastLine.time
        ? Math.min(lastLine.time + spokenDuration, duration)
        : lastLine.time + spokenDuration;
    }
  }
  if (parsedLyrics[0].time !== null && audio.currentTime < parsedLyrics[0].time) {
    content.classList.add("waiting-for-lyrics");
    content.appendChild(createLyricsLoading(lang === "en" ? "Waiting for vocals…" : "Ждём начала вокала…"));
  }
  parsedLyrics.forEach((line, index) => {
    const item = document.createElement("p");
    item.className = line.pause ? "lyrics-line lyrics-pause" : "lyrics-line";
    item.textContent = line.text;
    if (line.time !== null) item.dataset.time = String(line.time);
    if (line.pause) {
      item.setAttribute("role", "status");
      item.setAttribute("aria-label", lang === "en" ? "Instrumental pause" : "Пауза без вокала");
      for (let i = 0; i < 3; i++) {
        const dot = document.createElement("span");
        dot.setAttribute("aria-hidden", "true");
        item.appendChild(dot);
      }
    }
    if (!line.pause) item.addEventListener("click", () => {
      if (line.time !== null && Number.isFinite(audio.duration)) seekAudio(line.time);
      else if (line.time !== null) seekAudio(line.time);
      if (line.time !== null) updateActiveLyric(true);
    });
    content.appendChild(item);
  });
  const credits = document.createElement("div");
  credits.className = "lyrics-credits";
  const source = document.createElement("div");
  source.textContent = lang === "en" ? "Lyrics source:" : "Источник текста:";
  credits.appendChild(source);
  const composer = document.createElement("div");
  const currentTrack = qIndex >= 0 ? queue[qIndex] : null;
  const artistName = data.artistName || (currentTrack && currentTrack.artist) || "";
  composer.textContent = (lang === "en" ? "Composer:" : "Композитор:") +
    (artistName ? " " + artistName : "");
  credits.appendChild(composer);
  content.appendChild(credits);
  updateActiveLyric(true);
}

function updateActiveLyric(forceScroll) {
  if (!parsedLyrics.length || parsedLyrics[0].time === null) return;
  const content = $("lyrics-content");
  const waitingForLyrics = audio.currentTime < parsedLyrics[0].time;
  content.classList.toggle("waiting-for-lyrics", waitingForLyrics);
  const loading = content.querySelector(".lyrics-loading");
  if (loading) {
    clearTimeout(lyricsLoadingTimer);
    lyricsLoadingTimer = null;
    if (waitingForLyrics) {
      loading.hidden = false;
      loading.classList.remove("fading");
    } else if (!loading.hidden && !loading.classList.contains("fading")) {
      loading.classList.add("fading");
      lyricsLoadingTimer = setTimeout(() => {
        if (loading.parentNode === content && !content.classList.contains("waiting-for-lyrics"))
          loading.hidden = true;
        loading.classList.remove("fading");
        lyricsLoadingTimer = null;
      }, 550);
    }
  }
  let index = -1;
  for (let i = 0; i < parsedLyrics.length; i++) {
    if (parsedLyrics[i].time > audio.currentTime) break;
    index = i;
  }
  if (audio.ended || audio.currentTime >= finalLyricEndTime) index = -1;
  if (index === activeLyricIndex && !forceScroll) return;
  activeLyricIndex = index;
  const lines = $("lyrics-content").querySelectorAll(".lyrics-line");
  lines.forEach((line, i) => {
    line.classList.toggle("active", i === index);
    line.classList.toggle("is-past", index >= 0 && i < index);
    const ahead = i - index - 1;
    const fade = index < 0 || ahead < 0 ? "" : String(Math.max(0, 0.72 - ahead * 0.14).toFixed(2));
    line.style.opacity = fade;
    line.style.pointerEvents = fade !== "" && parseFloat(fade) < 0.15 ? "none" : "";
  });
  if (index >= 0) followActiveLyric();
}

function followActiveLyric() {
  if (lyricsScrollFrame) return;
  const content = $("lyrics-content");
  const animate = () => {
    const line = content.querySelectorAll(".lyrics-line")[activeLyricIndex];
    if (!line || !content.isConnected) {
      lyricsScrollFrame = 0;
      return;
    }
    const containerBounds = content.getBoundingClientRect();
    const lineBounds = line.getBoundingClientRect();
    const target = content.scrollTop + lineBounds.top - containerBounds.top -
      content.clientHeight / 2 + lineBounds.height / 2;
    const difference = target - content.scrollTop;
    if (Math.abs(difference) < 0.5) {
      content.scrollTop = target;
      lyricsScrollFrame = 0;
      return;
    }
    content.scrollTop += difference * 0.18;
    lyricsScrollFrame = requestAnimationFrame(animate);
  };
  lyricsScrollFrame = requestAnimationFrame(animate);
}

