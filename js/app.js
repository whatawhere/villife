async function refreshSpotifyPlaylistTracks(playlist, loadId) {
  const tracks = activePlaylistTracks;
  let next = 0;
  const worker = async () => {
    while (true) {
      const index = next++;
      if (index >= tracks.length) return;
      const track = tracks[index];
      if (!track || track.source !== "spotify" || track.spotifyMetadataVersion === 4) continue;
      try {
        await ensureSpotifyTrackResolved(track);
      } catch (error) {
        console.error("Could not refresh imported Spotify track.", track.id, error);
      }
    }
  };
  await Promise.all(Array(Math.min(4, tracks.length)).fill(0).map(worker));
  if (loadId !== playlistLoadId || activePlaylist !== playlist) return;
  savePlaylists();
  renderPlaylistDetail(playlist, tracks);
  warmTracks(tracks.slice(0, 3));
}

async function refreshSpotifyLibraryTracks() {
  if (spotifyLibraryRefreshing) return;
  const tracks = lib.filter(track => track && track.source === "spotify" && track.spotifyMetadataVersion !== 4);
  if (!tracks.length) return;
  spotifyLibraryRefreshing = true;
  tracks.forEach(track => {
    track.stream = "";
    track.preview = "";
    track.artwork = "";
  });
  renderLibrary();

  let next = 0;
  const worker = async () => {
    while (true) {
      const index = next++;
      if (index >= tracks.length) return;
      const track = tracks[index];
      try {
        await ensureSpotifyTrackResolved(track);
      } catch (error) {
        console.error("Could not refresh imported Spotify track.", track.id, error);
      }
    }
  };
  try {
    await Promise.all(Array(Math.min(3, tracks.length)).fill(0).map(worker));
    saveLib();
    renderLibrary();
  } finally {
    spotifyLibraryRefreshing = false;
  }
}

