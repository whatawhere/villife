function addToQueue(track) {
  if (!track) return;
  if (queue.some((queued, index) => index > qIndex && sameTrack(queued, track))) return;
  if (qIndex >= 0) queue.splice(qIndex + 1, 0, track);
  else queue.push(track);
  if (view === "queue") renderQueue();
  updateSection();
  toast(ht("queue_added"));
}

function recordHistory(track) {
  if (!track) return;
  if (historyTracks.length && sameTrack(historyTracks[0], track)) return;
  historyTracks = [track].concat(historyTracks.filter(item => !sameTrack(item, track))).slice(0, 100);
  try {
    localStorage.setItem("velo_history", JSON.stringify(historyTracks));
  } catch (error) {
    console.error("Could not save playback history.", error);
    toast(lang === "en" ? "Could not save playback history" : "Не удалось сохранить историю прослушивания");
  }
  if (view === "history") renderHistory();
  if (view === "search" && !lastQuery.trim()) renderRecentHome();
}

