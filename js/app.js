function updateProgress() {
  const duration = Number.isFinite(audio.duration) ? audio.duration : 0;
  const displayedTime = seeking && seekPreviewTime !== null ? seekPreviewTime : audio.currentTime || 0;
  const current = Math.min(duration, Math.max(0, displayedTime));
  const percent = duration ? current / duration * 100 : 0;
  $("wave-progress-fill").style.width = percent + "%";
  $("pl-fill").style.width = percent + "%";
  if (document.body.classList.contains("fullscreen-on")) {
    $("np-fill").style.width = percent + "%";
    $("np-cur").textContent = fmt(current);
    $("np-dur").textContent = fmt(duration);
  }
  $("pl-bar").setAttribute("aria-valuemax", String(duration));
  $("pl-bar").setAttribute("aria-valuenow", String(current));
  $("pl-bar").setAttribute("aria-valuetext", fmt(current) + " / " + fmt(duration));
}

function bindAudioEvents(element) {
  const onActive = handler => event => {
    if (element === audio) handler(event);
  };
  element.addEventListener("play", onActive(renderPlayer));
  element.addEventListener("pause", onActive(renderPlayer));
  element.addEventListener("play", onActive(() => {
    if (mediaSession) mediaSession.playbackState = "playing";
    updateMediaPosition(true);
  }));
  element.addEventListener("pause", onActive(() => {
    if (mediaSession) mediaSession.playbackState = "paused";
    updateMediaPosition(true);
  }));
  element.addEventListener("loadedmetadata", onActive(() => {
    $("pl-bar").setAttribute("aria-valuemax", String(audio.duration || 0));
    $("pl-dur").textContent = fmt(audio.duration);
    updateProgress();
    updateMediaPosition(true);
    updateDiscordPresence();
  }));
  element.addEventListener("error", () => {
    if (element === audio) {
      if (recoverCrossfade(audio.error)) return;
      if (audio.error && audio.error.code === 1) return;
      console.error("Audio stream failed to load.", audio.error);
      toast(t("playback_error"));
      return;
    }
    if (element === standbyAudio && crossfadePending) {
      abortPendingCrossfade(element.error);
    }
  });
  element.addEventListener("timeupdate", onActive(() => {
    $("pl-cur").textContent = fmt(seeking && seekPreviewTime !== null ? seekPreviewTime : audio.currentTime);
    updateProgress();
    updateActiveLyric(false);
    updateMediaPosition(false);
    maybeCrossfadeAtTrackEnd();
  }));
  element.addEventListener("seeked", onActive(() => {
    updateActiveLyric(true);
    updateDiscordPresence();
  }));
  element.addEventListener("waiting", onActive(updateDiscordPresence));
  element.addEventListener("playing", onActive(() => {
    updateDiscordPresence();
    recordHistory(qIndex >= 0 ? queue[qIndex] : null);
  }));
  element.addEventListener("ended", onActive(() => {
    if (mediaSession) mediaSession.playbackState = "paused";
    updateActiveLyric(true);
    updateDiscordPresence();
    if (qIndex >= 0 && queue[qIndex]) recordWaveCompletion(queue[qIndex]);
    if (repeatMode !== "off" || $("settings-autoplay").checked) step(1, true);
  }));
}

