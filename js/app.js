function normalizeTrackTitle(track, artistNames) {
  let title = String(track.title || "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "").trim();
  const removedVersion = /\b(?:prod(?:uced)?\.?|slowed|sped[\s-]*up|bass[\s-]*boost(?:ed)?|nightcore|reverb|8d)\b/i.test(title);
  title = title
    .replace(/\s*[\[(]\s*(?:available on all platforms|на всех площадках)\s*[\])]\s*$/i, "")
    .replace(/\s*[\[(]\s*(?:produced by|prod(?:uced)?\.?)\s+[^)\]]+[\])]\s*$/i, "")
    .replace(/\s*[-–—|]\s*(?:produced by|prod(?:uced)?\.?)\s+.*$/i, "")
    .replace(/\s*#\w+\s*$/u, "")
    .replace(/\s+/g, " ")
    .replace(/^[\s\-–—|:]+|[\s\-–—|:]+$/g, "")
    .trim();

  const artist = String(track.artist || "").trim();
  const knownArtists = (artistNames || []).concat(artist ? [artist] : [])
    .sort((a, b) => b.length - a.length);
  knownArtists.forEach(name => {
    const escapedArtist = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    title = title
      .replace(new RegExp("^" + escapedArtist + "\\s*[-–—:|,+&]+\\s*", "i"), "")
      .replace(new RegExp("\\s*[-–—:|,+&]+\\s*" + escapedArtist + "$", "i"), "")
      .trim();
  });
  title = title.replace(/\s*(?:w\/|with)\s*$/i, "").trim();

  const key = title.toLocaleLowerCase().replace(/[^\w\u00c0-\u024f\u0400-\u04ff]+/g, " ").trim();
  const artistKey = artist.toLocaleLowerCase().replace(/[^\w\u00c0-\u024f\u0400-\u04ff]+/g, " ").trim();
  return { track: Object.assign({}, track, { title: title || track.title }), key: key, artistKey: artistKey, version: removedVersion };
}

function uniqueSearchTracks(tracks) {
  const unique = [];
  const artistNames = tracks.map(track => String(track.artist || "").trim())
    .filter((artist, index, artists) => artist && artists.indexOf(artist) === index);
  tracks.forEach(track => {
    const normalized = normalizeTrackTitle(track, artistNames);
    const duplicate = unique.some(item => {
      if (!normalized.key || normalized.key !== item.key) return false;
      if (normalized.artistKey && normalized.artistKey === item.artistKey) return true;
      if (normalized.version || item.version) return true;
      const duration = Number(normalized.track.duration) || 0;
      const otherDuration = Number(item.track.duration) || 0;
      return duration > 0 && otherDuration > 0 &&
        Math.abs(duration - otherDuration) <= Math.max(12, Math.min(duration, otherDuration) * 0.16);
    });
    if (!duplicate) unique.push(normalized);
  });
  return unique.map(item => item.track);
}

