async function ensureAudioGraph() {
  if (!audioContext) {
    const AudioContextConstructor = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextConstructor) throw new Error("Web Audio is not supported.");
    audioContext = new AudioContextConstructor();
    [audioDeck, standbyDeck].forEach((deck, index) => {
      deck.source = audioContext.createMediaElementSource(deck.element);
      deck.gain = audioContext.createGain();
      deck.gain.gain.value = index === 0 ? 1 : 0;
      deck.source.connect(deck.gain);
      deck.gain.connect(audioContext.destination);
    });
  }
  if (audioContext.state === "closed") throw new Error("The audio context is closed.");
  if (audioContext.state !== "running") await audioContext.resume();
}

function clampVolume(value) {
  const numeric = Number(value);
  if (!Number.isFinite(numeric)) return 0.8;
  return Math.min(1, Math.max(0, numeric));
}

function syncVolumeUi() {
  const current = clampVolume(audio.volume);
  const percent = Math.round(current * 100);
  const sliders = [$("pl-vol"), $("settings-volume")];
  sliders.forEach(slider => {
    if (!slider) return;
    slider.value = String(current);
    slider.style.setProperty("--value", percent + "%");
  });
  const percentText = $("settings-volume-value");
  if (percentText) percentText.value = percent + "%";
  const playerValue = $("pl-volume-value");
  if (playerValue) playerValue.textContent = percent + "%";
}

