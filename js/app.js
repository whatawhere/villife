function updatePlaylistEdges() {
  const maxScroll = playlistScroller.scrollWidth - playlistScroller.clientWidth;
  const scrollLeft = playlistScroller.scrollLeft;
  const delta = scrollLeft - previousPlaylistScrollLeft;
  if (Math.abs(delta) > 0.5) playlistFadeDirection = delta > 0 ? 1 : -1;
  previousPlaylistScrollLeft = scrollLeft;

  const noOverflow = maxScroll <= 1;
  const atStart = scrollLeft <= 1;
  const atEnd = scrollLeft >= maxScroll - 1;
  if (noOverflow || atStart || atEnd) playlistFadeDirection = 0;

  playlistRail.classList.toggle("no-overflow", noOverflow);
  playlistRail.classList.toggle("at-start", atStart);
  playlistRail.classList.toggle("at-end", atEnd);
  playlistRail.classList.toggle("show-left-fade", playlistFadeDirection === -1);
  playlistRail.classList.toggle("show-right-fade", playlistFadeDirection === 1);
}

playlistScroller.addEventListener("scroll", updatePlaylistEdges, { passive: true });
window.addEventListener("resize", updatePlaylistEdges);
if ("ResizeObserver" in window) {
  const playlistResizeObserver = new ResizeObserver(updatePlaylistEdges);
  playlistResizeObserver.observe(playlistScroller);
}

playlistScroller.addEventListener("wheel", e => {
  if (playlistScroller.scrollWidth <= playlistScroller.clientWidth ||
      Math.abs(e.deltaY) <= Math.abs(e.deltaX)) return;
  e.preventDefault();
  const delta = e.deltaY * (e.deltaMode === WheelEvent.DOM_DELTA_LINE ? 16 :
    e.deltaMode === WheelEvent.DOM_DELTA_PAGE ? playlistScroller.clientWidth : 1);
  playlistScroller.scrollBy({ left: delta, behavior: "smooth" });
}, { passive: false });

playlistScroller.addEventListener("pointerdown", e => {
  if (e.button !== 0 || playlistScroller.scrollWidth <= playlistScroller.clientWidth) return;
  const captureTarget = e.target.closest("[data-playlist]") || playlistScroller;
  playlistDrag = { x: e.clientX, scrollLeft: playlistScroller.scrollLeft, moved: false, captureTarget: captureTarget };
  captureTarget.setPointerCapture(e.pointerId);
});

playlistScroller.addEventListener("pointermove", e => {
  if (!playlistDrag) return;
  const distance = e.clientX - playlistDrag.x;
  if (Math.abs(distance) > 5) {
    playlistDrag.moved = true;
    playlistScroller.classList.add("dragging");
  }
  if (playlistDrag.moved) {
    playlistScroller.scrollLeft = playlistDrag.scrollLeft - distance;
    e.preventDefault();
  }
});

function finishPlaylistDrag(e) {
  if (!playlistDrag) return;
  if (playlistDrag.moved) suppressPlaylistClick = true;
  const captureTarget = playlistDrag.captureTarget;
  playlistDrag = null;
  playlistScroller.classList.remove("dragging");
  if (captureTarget.hasPointerCapture(e.pointerId))
    captureTarget.releasePointerCapture(e.pointerId);
  if (suppressPlaylistClick)
    setTimeout(() => { suppressPlaylistClick = false; }, 0);
}

